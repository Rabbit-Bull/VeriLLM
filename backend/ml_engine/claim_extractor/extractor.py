"""
VeriLLM Unified Claim Extractor Module.
Orchestrates sentence segmentation, clause decomposition, coreference resolution, and proposition filtering.
"""

from typing import List, Optional
from .models import ExtractedClaim, ExtractionResult
from .sentence_splitter import split_sentences_with_spans, SentenceSpan
from .proposition_decomposer import (
    decompose_sentence, 
    extract_salient_subject,
    extract_named_entities,
    get_nlp
)
from .claim_filter import classify_proposition


class ClaimExtractor:
    """
    Main extraction interface.
    Transforms raw multi-sentence LLM responses into fine-grained atomic factual claims
    while preserving full source offsets and traceability.
    """

    def __init__(
        self,
        resolve_coreference: bool = True,
        decompose_compound: bool = True,
        include_non_factual: bool = True
    ):
        self.resolve_coreference = resolve_coreference
        self.decompose_compound = decompose_compound
        self.include_non_factual = include_non_factual
        # Pre-warm spaCy model
        self.nlp = get_nlp()

    def extract_claims(self, text: str) -> ExtractionResult:
        """
        Decomposes a response text into a list of atomic claims.

        Args:
            text: The full string generated by an LLM or provided by a user.

        Returns:
            ExtractionResult containing structured ExtractedClaim objects and aggregate statistics.
        """
        if not text or not text.strip():
            return ExtractionResult(raw_text=text or "")

        sentence_spans = split_sentences_with_spans(text)
        extracted_claims: List[ExtractedClaim] = []
        
        current_salient_subject: Optional[str] = None
        claim_counter = 1

        for sent_span in sentence_spans:
            sent_text = sent_span.text
            start_char = sent_span.start_char
            end_char = sent_span.end_char

            # 1. Decompose sentence into atomic propositions
            if self.decompose_compound:
                propositions = decompose_sentence(
                    sentence_text=sent_text,
                    previous_subject=current_salient_subject if self.resolve_coreference else None
                )
            else:
                from .proposition_decomposer import AtomicProposition
                propositions = [AtomicProposition(text=sent_text)]

            # 2. Update salient subject for subsequent sentence coreference
            detected_subject = extract_salient_subject(sent_text)
            if detected_subject:
                current_salient_subject = detected_subject

            # 3. Classify and package each proposition
            for prop in propositions:
                prop_text = prop.text

                # Classify factuality
                is_factual, claim_type, filter_meta = classify_proposition(prop_text)

                if not self.include_non_factual and not is_factual:
                    continue

                # Extract named entities via spaCy
                prop_doc = self.nlp(prop_text)
                entities = extract_named_entities(prop_doc)

                claim_id = f"claim_{claim_counter:03d}"
                claim_counter += 1

                combined_metadata = {
                    **prop.metadata,
                    **filter_meta,
                    "clause_type": prop.clause_type
                }

                # Compute absolute claim-level offsets within raw response text
                if prop.clause_start is not None and prop.clause_end is not None:
                    claim_start_char = start_char + prop.clause_start
                    claim_end_char = start_char + prop.clause_end
                else:
                    claim_start_char = start_char
                    claim_end_char = end_char

                claim = ExtractedClaim(
                    claim_id=claim_id,
                    text=prop_text,
                    source_sentence=sent_text,
                    start_char=start_char,
                    end_char=end_char,
                    claim_start_char=claim_start_char,
                    claim_end_char=claim_end_char,
                    offset_type=prop.offset_type,
                    is_factual=is_factual,
                    claim_type=claim_type,
                    has_negation=filter_meta.get("has_negation", False),
                    has_numbers=filter_meta.get("has_numbers", False),
                    named_entities=entities,
                    metadata=combined_metadata
                )
                extracted_claims.append(claim)

        factual_count = sum(1 for c in extracted_claims if c.is_factual)
        non_factual_count = len(extracted_claims) - factual_count

        return ExtractionResult(
            raw_text=text,
            claims=extracted_claims,
            total_sentences=len(sentence_spans),
            factual_claims_count=factual_count,
            non_factual_count=non_factual_count
        )

