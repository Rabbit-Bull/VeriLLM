"""
VeriLLM Live LLM Generation Schemas.
Pydantic data models for candidate response generation requests, results, and error tracking.
"""

from __future__ import annotations

from typing import Any, Dict, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class GenerationRequest(BaseModel):
    """Input payload requesting response generation from an external LLM."""

    question: str = Field(
        ...,
        description="The prompt or question to be answered by the LLM.",
        min_length=1,
    )
    model: Optional[str] = Field(
        default=None,
        description="Optional model identifier override (e.g. 'gemini-3.8-flash').",
    )
    temperature: Optional[float] = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature for text generation.",
    )
    max_output_tokens: Optional[int] = Field(
        default=1024,
        gt=0,
        le=8192,
        description="Maximum tokens to generate.",
    )
    system_instruction: Optional[str] = Field(
        default=None,
        description="Optional system instruction for guiding model behavior.",
    )

    @field_validator("question")
    @classmethod
    def validate_non_empty_question(cls, v: str) -> str:
        stripped = v.strip() if v else ""
        if not stripped:
            raise ValueError("Question cannot be empty or whitespace.")
        return stripped


class GenerationError(BaseModel):
    """Structured error information when response generation fails."""

    error_code: str = Field(
        ...,
        description="Machine-readable error category (e.g. 'MISSING_API_KEY', 'AUTH_FAILURE', 'QUOTA_EXCEEDED', 'TIMEOUT').",
    )
    message: str = Field(
        ...,
        description="Human-readable description of the error.",
    )
    details: Optional[str] = Field(
        default=None,
        description="Additional technical diagnostics (without sensitive credentials).",
    )
    retryable: bool = Field(
        default=False,
        description="Whether the client should attempt a retry (e.g. for rate limits or timeouts).",
    )


class GenerationResult(BaseModel):
    """Structured result returned by LLM generation providers."""

    question: str = Field(
        ...,
        description="The original user question or prompt.",
    )
    response_text: str = Field(
        default="",
        description="Candidate text generated by the model.",
    )
    model_id: str = Field(
        ...,
        description="Canonical identifier of the model that generated the response.",
    )
    execution_time_seconds: float = Field(
        default=0.0,
        description="Wall-clock elapsed time in seconds for the generation request.",
    )
    success: bool = Field(
        default=True,
        description="True if generation succeeded and produced non-empty text, False otherwise.",
    )
    finish_reason: Optional[str] = Field(
        default=None,
        description="Reason generation concluded (e.g. 'STOP', 'MAX_TOKENS', 'SAFETY').",
    )
    prompt_tokens: Optional[int] = Field(
        default=None,
        description="Number of tokens in the input prompt.",
    )
    candidates_tokens: Optional[int] = Field(
        default=None,
        description="Number of tokens in the generated response.",
    )
    total_tokens: Optional[int] = Field(
        default=None,
        description="Total token consumption for the request.",
    )
    usage_metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Token consumption metadata dictionary (prompt_token_count, candidates_token_count, total_token_count).",
    )
    error: Optional[GenerationError] = Field(
        default=None,
        description="Structured error information if generation failed.",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional provider-specific metadata and diagnostics.",
    )

    @model_validator(mode="after")
    def sync_usage_metadata(self) -> GenerationResult:
        """Ensures bidirectional consistency between token fields and usage_metadata."""
        if self.usage_metadata is not None:
            if self.prompt_tokens is None and "prompt_token_count" in self.usage_metadata:
                self.prompt_tokens = self.usage_metadata.get("prompt_token_count")
            if self.candidates_tokens is None and "candidates_token_count" in self.usage_metadata:
                self.candidates_tokens = self.usage_metadata.get("candidates_token_count")
            if self.total_tokens is None and "total_token_count" in self.usage_metadata:
                self.total_tokens = self.usage_metadata.get("total_token_count")
        elif any(t is not None for t in (self.prompt_tokens, self.candidates_tokens, self.total_tokens)):
            self.usage_metadata = {
                "prompt_token_count": self.prompt_tokens,
                "candidates_token_count": self.candidates_tokens,
                "total_token_count": self.total_tokens,
            }
        return self

    def to_dict(self) -> Dict[str, Any]:
        """Serializes the result to a standard dictionary."""
        return self.model_dump()

